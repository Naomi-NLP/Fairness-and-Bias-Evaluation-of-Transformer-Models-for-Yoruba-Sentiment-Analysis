def prepare_data(data, text_column='yo_review'):
    """
    Prepare data for training
    text_column: choose 'en_review', 'yo_review', or 'yo_mt_review'
    """
    # Convert sentiment to numerical labels (BINARY: 0 and 1)
    label_map = {'negative': 0, 'positive': 1}
    data = data.copy()
    data['label'] = data['sentiment'].map(label_map)

    # Check for any unmapped values
    if data['label'].isnull().any():
        print("⚠️ Warning: Found unmapped sentiment values!")
        print(data['sentiment'].unique())
        return None, None, None

    # Train-test split (stratified to maintain class balance)
    train_df, test_df = train_test_split(
        data,
        test_size=0.2,
        stratify=data['label'],
        random_state=42
    )

    # Validation split from training
    train_df, val_df = train_test_split(
        train_df,
        test_size=0.15,
        stratify=train_df['label'],
        random_state=42
    )

    print(f"  Data split complete:")
    print(f"  Train: {len(train_df)} samples")
    print(f"  Validation: {len(val_df)} samples")
    print(f"  Test: {len(test_df)} samples")

    # Check class distribution
    print(f"\nTrain set distribution:")
    print(train_df['sentiment'].value_counts())
    print(f"\nValidation set distribution:")
    print(val_df['sentiment'].value_counts())
    print(f"\nTest set distribution:")
    print(test_df['sentiment'].value_counts())

    return train_df, val_df, test_df

