from scipy import stats

# McNemar's test to compare models
def mcnemar_test(model1_preds, model2_preds, true_labels):
    """
    McNemar's test for comparing two classifiers
    Tests if the difference in performance is statistically significant
    """
    # Create contingency table
    # Both correct, Model1 correct & Model2 wrong, Model1 wrong & Model2 correct, Both wrong
    both_correct = ((model1_preds == true_labels) & (model2_preds == true_labels)).sum()
    m1_correct_m2_wrong = ((model1_preds == true_labels) & (model2_preds != true_labels)).sum()
    m1_wrong_m2_correct = ((model1_preds != true_labels) & (model2_preds == true_labels)).sum()
    both_wrong = ((model1_preds != true_labels) & (model2_preds != true_labels)).sum()

    # McNemar's statistic
    # Uses only disagreements (b and c in contingency table)
    if m1_correct_m2_wrong + m1_wrong_m2_correct == 0:
        return None, 1.0  # No disagreements, models are identical

    statistic = ((abs(m1_correct_m2_wrong - m1_wrong_m2_correct) - 1) ** 2) / (m1_correct_m2_wrong + m1_wrong_m2_correct)
    p_value = 1 - stats.chi2.cdf(statistic, df=1)

    return statistic, p_value

