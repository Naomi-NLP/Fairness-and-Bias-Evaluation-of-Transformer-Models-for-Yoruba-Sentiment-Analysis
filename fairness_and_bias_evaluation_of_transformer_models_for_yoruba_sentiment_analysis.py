def train_model(train_df, val_df, text_column, model_name='xlm-roberta-base', output_dir='./results/xlm_roberta'):
    """
    Train the sentiment analysis model using XLM-RoBERTa

    Parameters:
    -----------
    train_df : pd.DataFrame
        Training dataframe
    val_df : pd.DataFrame
        Validation dataframe
    text_column : str
        Column name containing text ('en_review', 'yo_review', 'yo_mt_review')
    model_name : str
        Model identifier (default: 'xlm-roberta-base')
    output_dir : str
        Directory to save model checkpoints

    Returns:
    --------
    trainer : Trainer
        Trained Hugging Face Trainer object
    tokenizer : AutoTokenizer
        Tokenizer used for the model
    model : AutoModelForSequenceClassification
        Trained model
    """

    print(f"Training {model_name} on {text_column}")


    # Initialize tokenizer and model
    print("Loading tokenizer and model...")
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForSequenceClassification.from_pretrained(
        model_name,
        num_labels=2  # BINARY: positive (1), negative (0)
    )

    print(" Model loaded successfully")
    print(f"  Model: {model_name}")
    print(f"  Number of parameters: {model.num_parameters():,}")

    # Prepare datasets
    print("\nPreparing datasets...")
    train_dataset = Dataset.from_pandas(
        train_df[[text_column, 'label']].rename(columns={text_column: 'text'})
    )
    val_dataset = Dataset.from_pandas(
        val_df[[text_column, 'label']].rename(columns={text_column: 'text'})
    )

    # Tokenize
    print("Tokenizing datasets...")
    train_dataset = train_dataset.map(
        lambda x: tokenize_function(x, tokenizer),
        batched=True,
        remove_columns=['text']
    )
    val_dataset = val_dataset.map(
        lambda x: tokenize_function(x, tokenizer),
        batched=True,
        remove_columns=['text']
    )

    print(" Tokenization complete")

    # Training arguments (FIXED for compatibility)
    training_args = TrainingArguments(
        output_dir=output_dir,
        eval_strategy='epoch',
        save_strategy='epoch',
        learning_rate=2e-5,
        per_device_train_batch_size=16,
        per_device_eval_batch_size=16,
        num_train_epochs=5,
        weight_decay=0.01,
        load_best_model_at_end=True,
        metric_for_best_model='f1',
        save_total_limit=2,
        logging_steps=10,
        warmup_steps=100,
        fp16=torch.cuda.is_available(),  # Use mixed precision if GPU available
        report_to='none',
    )

    # Metrics
    def compute_metrics(eval_pred):
        predictions, labels = eval_pred
        predictions = np.argmax(predictions, axis=1)

        return {
            'accuracy': accuracy_score(labels, predictions),
            'f1': f1_score(labels, predictions, average='binary'),
            'precision': precision_score(labels, predictions, average='binary'),
            'recall': recall_score(labels, predictions, average='binary')
        }

    # Trainer
    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=train_dataset,
        eval_dataset=val_dataset,
        compute_metrics=compute_metrics,
        callbacks=[EarlyStoppingCallback(early_stopping_patience=2)]
    )

    # Train
    print("\n Starting training...\n")
    trainer.train()

    print("\n Training complete!")

    return trainer, tokenizer, model

